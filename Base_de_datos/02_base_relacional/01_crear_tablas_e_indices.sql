CREATE TABLE IF NOT EXISTS public.turnos (
 nombre text PRIMARY KEY,
 inicio time NOT NULL, fin time NOT NULL,
 normal_hasta time NOT NULL, tarde_desde time NOT NULL, tarde_hasta time NOT NULL,
 ausente_desde time NOT NULL, presencia_desde time NOT NULL,
 CHECK (inicio <= normal_hasta AND normal_hasta < tarde_desde AND tarde_desde <= tarde_hasta AND tarde_hasta < ausente_desde AND ausente_desde < presencia_desde AND presencia_desde < fin)
);
CREATE TABLE IF NOT EXISTS public.cursos (
 codigo text PRIMARY KEY, anio smallint NOT NULL CHECK (anio BETWEEN 1 AND 6),
 division smallint NOT NULL CHECK (division > 0), turno text NOT NULL REFERENCES public.turnos(nombre),
 especialidad text NOT NULL, UNIQUE (anio, division, especialidad)
);
CREATE TABLE IF NOT EXISTS public.alumnos (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre text NOT NULL, apellido text NOT NULL, dni text NOT NULL UNIQUE,
 curso_codigo text NOT NULL REFERENCES public.cursos(codigo),
 email text, email_responsable text, codigo_qr text NOT NULL UNIQUE,
 fecha_alta date NOT NULL
);
CREATE TABLE IF NOT EXISTS public.preceptores (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre text NOT NULL, apellido text NOT NULL, email text
);
CREATE TABLE IF NOT EXISTS public.usuarios (
 usuario text PRIMARY KEY, rol text NOT NULL CHECK (rol IN ('alumno','preceptor','jefa')),
 nombre text NOT NULL, apellido text NOT NULL,
 alumno_id bigint UNIQUE REFERENCES public.alumnos(id),
 preceptor_id bigint UNIQUE REFERENCES public.preceptores(id),
 auth_id uuid UNIQUE, activo boolean NOT NULL DEFAULT true,
 CHECK ((rol='alumno' AND alumno_id IS NOT NULL AND preceptor_id IS NULL) OR
 (rol='preceptor' AND preceptor_id IS NOT NULL AND alumno_id IS NULL) OR
 (rol='jefa' AND alumno_id IS NULL AND preceptor_id IS NULL))
);
CREATE TABLE IF NOT EXISTS public.asignaciones (
 curso_codigo text PRIMARY KEY REFERENCES public.cursos(codigo),
 preceptor_id bigint NOT NULL REFERENCES public.preceptores(id)
);
CREATE TABLE IF NOT EXISTS public.bimestres (
 anio smallint NOT NULL, numero smallint NOT NULL CHECK (numero BETWEEN 1 AND 4),
 inicio date NOT NULL, fin date NOT NULL, limite_faltas numeric(5,2) NOT NULL DEFAULT 5,
 PRIMARY KEY (anio,numero), CHECK (inicio <= fin), CHECK (limite_faltas > 0)
);
CREATE TABLE IF NOT EXISTS public.horarios (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 curso_codigo text NOT NULL REFERENCES public.cursos(codigo),
 dia_semana smallint NOT NULL CHECK (dia_semana BETWEEN 1 AND 5),
 sesion text NOT NULL CHECK (sesion IN ('principal','contraturno','educacion_fisica')),
 inicio time NOT NULL, fin time NOT NULL, observacion text,
 UNIQUE(curso_codigo,dia_semana,sesion), CHECK (inicio < fin)
);
CREATE TABLE IF NOT EXISTS public.calendario_escolar (
 fecha date PRIMARY KEY, motivo text NOT NULL, tipo text NOT NULL CHECK (tipo IN ('feriado','asueto','receso','suspension'))
);
CREATE TABLE IF NOT EXISTS public.asistencias (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 alumno_id bigint NOT NULL REFERENCES public.alumnos(id),
 fecha date NOT NULL, sesion text NOT NULL DEFAULT 'principal' CHECK (sesion IN ('principal','contraturno','educacion_fisica')),
 entrada time, salida time,
 estado text NOT NULL CHECK (estado IN ('Presente','Ausente','Tarde','Retiro','Justificado','Sin registrar')),
 tipo text NOT NULL, observacion text,
 es_simulado boolean NOT NULL DEFAULT false,
 UNIQUE(alumno_id,fecha,sesion), CHECK (salida IS NULL OR entrada IS NULL OR salida >= entrada)
);
CREATE TABLE IF NOT EXISTS public.justificaciones (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 asistencia_id bigint NOT NULL REFERENCES public.asistencias(id),
 tipo text NOT NULL CHECK (tipo IN ('medica','familiar','deportiva','otra')),
 motivo text NOT NULL DEFAULT '', estado text NOT NULL CHECK (estado IN ('En revisión','Justificado','Denegado')),
 observacion_revision text, archivo_nombre text, archivo_ruta text,
 presentado_por text REFERENCES public.usuarios(usuario), presentado_el timestamptz,
 revisado_por text REFERENCES public.usuarios(usuario), revisado_el timestamptz
);
CREATE UNIQUE INDEX IF NOT EXISTS et35_justificacion_vigente ON public.justificaciones(asistencia_id) WHERE estado IN ('En revisión','Justificado');
CREATE TABLE IF NOT EXISTS public.movimientos_matricula (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 alumno_id bigint NOT NULL REFERENCES public.alumnos(id), fecha date NOT NULL,
 tipo text NOT NULL CHECK (tipo IN ('baja','reingreso')), motivo text NOT NULL,
 usuario text REFERENCES public.usuarios(usuario)
);
CREATE TABLE IF NOT EXISTS public.ajustes_bimestrales (
 alumno_id bigint NOT NULL REFERENCES public.alumnos(id), anio smallint NOT NULL, bimestre smallint NOT NULL,
 valor numeric(6,2) NOT NULL CHECK (mod(valor,0.25)=0),
 PRIMARY KEY(alumno_id,anio,bimestre), FOREIGN KEY(anio,bimestre) REFERENCES public.bimestres(anio,numero)
);
CREATE TABLE IF NOT EXISTS public.registros_qr (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 asistencia_id bigint NOT NULL REFERENCES public.asistencias(id),
 movimiento text NOT NULL CHECK (movimiento IN ('Entrada','Salida')), registrado_el timestamptz NOT NULL DEFAULT now(),
 UNIQUE(asistencia_id,movimiento)
);
CREATE TABLE IF NOT EXISTS public.auditoria (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 fecha timestamptz NOT NULL DEFAULT now(), usuario text REFERENCES public.usuarios(usuario), accion text NOT NULL, detalle text
);
CREATE TABLE IF NOT EXISTS public.notificaciones (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 alumno_id bigint NOT NULL REFERENCES public.alumnos(id), usuario text REFERENCES public.usuarios(usuario),
 fecha timestamptz NOT NULL DEFAULT now(), email text, tipo text NOT NULL,
 estado text NOT NULL DEFAULT 'Borrador' CHECK (estado IN ('Borrador','Enviado','Error'))
);
CREATE INDEX IF NOT EXISTS et35_alumnos_curso ON public.alumnos(curso_codigo);
CREATE INDEX IF NOT EXISTS et35_alumnos_apellido ON public.alumnos(apellido);
CREATE INDEX IF NOT EXISTS et35_asistencias_fecha ON public.asistencias(fecha);
CREATE INDEX IF NOT EXISTS et35_matricula_alumno_fecha ON public.movimientos_matricula(alumno_id,fecha);

